-- =====================================================================
-- QuickCart database (PostgreSQL 16)
-- Runs automatically the FIRST time the db container starts
-- (only when the pg-data volume is new). Baked into the image by db/Dockerfile.
-- To reset the data on a dev machine: docker compose down -v
-- =====================================================================


-- 1. Products sold in the store
CREATE TABLE IF NOT EXISTS products (
  product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(60) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(255) NOT NULL,
  category VARCHAR(50) NOT NULL,
  price DECIMAL(10,2) NOT NULL CHECK (price > 0),        -- current selling price (USD)
  list_price DECIMAL(10,2) NULL,                         -- original price (shown crossed out when higher)
  rating DECIMAL(2,1) NOT NULL DEFAULT 4.5,
  reviews INT NOT NULL DEFAULT 0,
  stock INT NOT NULL CHECK (stock >= 0),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Customers (created at checkout; address saved only if the customer ticks "save")
CREATE TABLE IF NOT EXISTS customers (
  customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(100) NOT NULL UNIQUE,
  full_name VARCHAR(100) NOT NULL,
  phone VARCHAR(30),
  street VARCHAR(150),
  city VARCHAR(80),
  state VARCHAR(80),
  zip VARCHAR(12),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Orders (one row per checkout; the shipping address is copied into the order)
CREATE TABLE IF NOT EXISTS orders (
  order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number VARCHAR(20) UNIQUE,                       -- e.g. QC-2026-88219
  customer_id INT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Processing',      -- Processing / Shipped / Delivered
  delivery_method VARCHAR(10) NOT NULL,                  -- standard / express
  subtotal DECIMAL(10,2) NOT NULL,
  discount DECIMAL(10,2) NOT NULL DEFAULT 0,
  shipping DECIMAL(10,2) NOT NULL DEFAULT 0,
  total DECIMAL(10,2) NOT NULL CHECK (total >= 0),
  payment_method VARCHAR(10) NOT NULL,                   -- card / paypal / gpay
  payment_reference VARCHAR(30) NOT NULL,
  ship_name VARCHAR(100) NOT NULL,
  ship_street VARCHAR(150) NOT NULL,
  ship_city VARCHAR(80) NOT NULL,
  ship_state VARCHAR(80) NOT NULL,
  ship_zip VARCHAR(12) NOT NULL,
  ship_phone VARCHAR(30) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

-- 4. Items inside each order (name and price are copied so old orders never change)
CREATE TABLE IF NOT EXISTS order_items (
  item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INT NOT NULL,
  product_id INT NOT NULL,
  product_name VARCHAR(100) NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL,
  quantity INT NOT NULL CHECK (quantity > 0),
  FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE CASCADE,
  FOREIGN KEY (product_id) REFERENCES products(product_id)
);

-- 5. Activity log (every order placed and every ticket is recorded)
CREATE TABLE IF NOT EXISTS activity_logs (
  log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INT NULL,
  action_type VARCHAR(50) NOT NULL,                      -- ORDER_PLACED / TICKET_CREATED
  info TEXT,
  logged_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE SET NULL
);

-- 6. Support tickets from the Contact page
CREATE TABLE IF NOT EXISTS support_tickets (
  ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL,
  subject VARCHAR(120) NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

